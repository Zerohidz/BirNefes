import com.zerohidz.whatsapppause.CallScreenGate;
import static com.zerohidz.whatsapppause.CallScreenGate.*;
public class CallScreenGateTest {
 static int checks;
 static void check(boolean value, String message) { checks++; if (!value) throw new AssertionError(message); }
 public static void main(String[] args) {
  check(IDLE==0&&RINGING==1&&OFFHOOK==2,"Values match TelephonyManager");
  CallScreenGate g = new CallScreenGate();
  check(!g.suppressOverlay(false),"Idle keeps the overlay");
  check(!g.callActive(false),"Idle is no call");
  check(!g.onCallState(IDLE),"Idle report needs no render");
  check(g.onCallState(RINGING),"Ringing start renders to hide the overlay");
  check(!g.onCallState(RINGING),"Repeated ringing needs no render");
  check(g.suppressOverlay(false),"Ringing hides the overlay");
  check(g.callActive(false),"Ringing is an active call");
  check(g.onCallState(IDLE),"Rejected or missed call renders the overlay back");
  check(!g.suppressOverlay(false),"Overlay returns after ringing");
  g.onCallState(RINGING);
  check(g.onCallState(OFFHOOK),"Answering leaves ringing and renders");
  check(!g.suppressOverlay(false),"Offhook is not a general suspension");
  check(g.callActive(false),"Offhook is an active call");
  check(g.onCallState(RINGING),"Waiting second call hides again");
  check(g.suppressOverlay(false),"Second call ringing hides");
  check(g.onCallState(OFFHOOK),"Second call answered renders");
  check(!g.onCallState(IDLE),"Offhook to idle was not ringing");
  check(!g.callActive(false),"Hang up ends the call");
  check(g.suppressOverlay(true),"Audio fallback hides without permission");
  check(g.callActive(true),"Audio fallback counts as a call");

  g = new CallScreenGate();
  g.screenOff(true);
  check(g.screenOn(false,false),"Unlocked screen-on after active gate goes Home");
  check(!g.screenOn(false,false),"Mark is single use");
  g.screenOff(false);
  check(!g.screenOn(false,false),"Away gate leaves no mark");
  g.screenOff(true);
  check(!g.screenOn(true,false),"Keyguard defers to the user-present path");
  check(!g.screenOn(false,false),"Keyguard consumed the mark");
  g.screenOff(true);
  check(!g.screenOn(false,true),"No Home during a call");
  check(!g.screenOn(false,false),"Call consumed the mark");
  g.screenOff(true);
  g.screenOff(false);
  check(g.screenOn(false,false),"A later away report keeps an unconsumed mark");
  g = new CallScreenGate();
  g.onCallState(RINGING);
  check(!g.answered()&&!g.ended(),"Ringing neither answers nor ends");
  g.onCallState(OFFHOOK);
  check(g.answered(),"Ringing to offhook is an answer");
  g.onCallState(OFFHOOK);
  check(!g.answered(),"Repeated offhook is no new answer");
  g.onCallState(IDLE);
  check(g.ended()&&!g.answered(),"Offhook to idle ends the call");
  g.onCallState(IDLE);
  check(!g.ended(),"Repeated idle is no new end");
  g.onCallState(OFFHOOK);
  check(!g.answered(),"Outgoing call is no answer");
  g.onCallState(RINGING);
  g.onCallState(IDLE);
  check(g.ended()&&!g.answered(),"Missed call ends without an answer");

  g = new CallScreenGate();
  check(!g.recheckAfterCall(false,false),"Nothing restricted under the call");
  g.window(true);
  check(!g.recheckAfterCall(false,true),"A new call postpones the check");
  check(g.recheckAfterCall(false,false),"Restricted app under the ended call is rechecked");
  check(!g.recheckAfterCall(false,false),"Recheck is one-shot");
  g.window(true); g.window(false);
  check(!g.recheckAfterCall(false,false),"Leaving the app clears the mark");
  g.window(true);
  check(!g.recheckAfterCall(true,false),"Lock screen uses the unlock path");
  check(!g.recheckAfterCall(false,false),"Locked outcome consumes the mark");
  g = new CallScreenGate();
  g.window(true); g.onCallState(RINGING); g.onCallState(OFFHOOK);
  check(g.recheckAfterAnswer(false),"Answer without a call screen rechecks the app in front");
  check(!g.recheckAfterAnswer(true),"Lock screen skips the answer recheck");
  g.callScreenWindow();
  check(!g.recheckAfterAnswer(false),"Visible call screen stays uncovered");
  g.window(true);
  check(g.recheckAfterAnswer(false),"Returning to the app during the call counts again");
  g.window(false);
  check(!g.recheckAfterAnswer(false),"Allowed app in front needs no recheck");
  g.window(true); g.onCallState(IDLE);
  check(!g.recheckAfterAnswer(false),"Ended call uses the after-call path");
  g = new CallScreenGate();
  g.window(true); g.onCallState(RINGING); g.callScreenWindow(); g.onCallState(OFFHOOK); g.onCallState(IDLE);
  g.onCallState(RINGING); g.onCallState(OFFHOOK);
  check(g.recheckAfterAnswer(false),"A new call forgets the old call screen");
  System.out.println(checks+" call screen checks passed");
 }
}
